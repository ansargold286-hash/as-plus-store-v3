const val SEVEN_DAYS_MILLIS: Long = 7L * 24L * 60L * 60L * 1000L

enum class PortalTab {
  Apps,
  Search,
}

data class PortalApp(
  val id: Int,
  val name: String,
  val developer: String,
  val category: String,
  val tab: PortalTab,
  val rating: String,
  val reviews: String,
  val ageRating: String,
  val sizeLabel: String,
  val version: String,
  val color: Color,
  val iconText: String,
  @DrawableRes val iconResId: Int? = null,
  @DrawableRes val bannerResId: Int? = null,
  val screenshotResIds: List<Int> = emptyList(),
  val heroTitle: String,
  val promoTitle: String,
  val promoText: String,
  val about: String,
  val downloadUrl: String,
  val isPlayStore: Boolean = false,
  val addedAtEpochMillis: Long,
  val featured: Boolean = false,
) {
  fun isRecent(nowMillis: Long = System.currentTimeMillis()): Boolean {
    val ageMillis = nowMillis - addedAtEpochMillis
    return ageMillis >= -86_400_000L && ageMillis < SEVEN_DAYS_MILLIS
  }
}

